#!/usr/bin/env python3
"""Generate crates/gml/src/builtins/generated.rs from specs/builtins.json.

Run from the repository root:  python crates/gml/tools/gen_builtins.py
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
SRC = os.path.join(ROOT, "specs", "builtins.json")
OUT = os.path.join(ROOT, "crates", "gml", "src", "builtins", "generated.rs")

# Constants whose value is null in the spec get distinct values in listing order
# within their family (see specs/OPEN_QUESTIONS.md, [IMPL-GML]).
NULL_FAMILIES = [
    ["os_win32", "os_win64", "os_macosx", "os_psp", "os_ios", "os_android"],
    ["device_ios_iphone", "device_ios_iphone_retina", "device_ios_ipad"],
    ["text_type", "button_type", "input_type"],
]

def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def rs_f64(v):
    r = repr(float(v))
    if "e" in r or "." in r or "inf" in r or "nan" in r:
        return r if ("e" not in r or "." in r) else r.replace("e", ".0e")
    return r + ".0"

def main():
    d = json.load(open(SRC, encoding="utf-8"))
    entries = d["entries"]
    funcs, vars_, consts = [], [], []
    seen = set()
    for e in entries:
        key = (e["name"], e["kind"])
        if key in seen:
            continue
        seen.add(key)
        {"function": funcs, "variable": vars_, "constant": consts}[e["kind"]].append(e)

    null_vals = {}
    for fam in NULL_FAMILIES:
        for i, n in enumerate(fam):
            null_vals[n] = i

    out = []
    w = out.append
    w("//! Built-in tables generated from `specs/builtins.json`.")
    w("// @generated by crates/gml/tools/gen_builtins.py. Do not edit.")
    w("#![allow(clippy::all, missing_docs)]")
    w("use super::{FunctionInfo, VariableInfo, ConstantInfo, VarScope, FunctionId, VariableId};")
    w("")
    w("/// Every built-in function, in `fnames` order. Indexed by [`FunctionId`].")
    w("pub static FUNCTIONS: &[FunctionInfo] = &[")
    for e in funcs:
        args = e.get("args") or []
        if e.get("variadic"):
            mn, mx = max(len(args) - 2, 0), 16
        else:
            mn = mx = len(args)
        w(f"    FunctionInfo {{ name: {rs_str(e['name'])}, min_args: {mn}, max_args: {mx}, variadic: {'true' if e.get('variadic') else 'false'}, chapter: {rs_str(str(e.get('chapter')))} }},")
    w("];")
    w("")
    w("/// Every built-in variable, in `fnames` order. Indexed by [`VariableId`].")
    w("pub static VARIABLES: &[VariableInfo] = &[")
    for e in vars_:
        scope = {"instance": "Instance", "global": "Global", "script": "Script"}[e["scope"]]
        arr = e.get("array")
        if arr:
            mx = arr.get("max")
            arr_s = f"Some(({arr['min']}, {mx if mx is not None else 'i32::MAX'}))"
        else:
            arr_s = "None"
        w(f"    VariableInfo {{ name: {rs_str(e['name'])}, scope: VarScope::{scope}, readonly: {'true' if e.get('readonly') else 'false'}, array: {arr_s} }},")
    w("];")
    w("")
    w("/// Every built-in constant with its value.")
    w("pub static CONSTANTS: &[ConstantInfo] = &[")
    for e in consts:
        v = e.get("value")
        inferred = e.get("value_source") != "manual"
        if v is None:
            v = null_vals.get(e["name"], 0)
            inferred = True
        w(f"    ConstantInfo {{ name: {rs_str(e['name'])}, value: {rs_f64(v)}, inferred: {'true' if inferred else 'false'} }},")
    w("];")
    w("")
    for mod, items, ty, doc in (("functions", funcs, "FunctionId", "function"), ("variables", vars_, "VariableId", "variable")):
        w(f"/// Named ids of every built-in {doc} (upper-cased name).")
        w(f"pub mod {mod} {{")
        w(f"    use super::{ty};")
        names = set()
        for i, e in enumerate(items):
            c = e["name"].upper()
            if c in names:
                sys.exit(f"name collision {c}")
            names.add(c)
            w(f"    pub const {c}: {ty} = {ty}({i});")
        w("}")
        w("")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(f"wrote {OUT}: {len(funcs)} functions, {len(vars_)} variables, {len(consts)} constants")

main()
