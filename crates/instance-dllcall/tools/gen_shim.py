"""Generates src/shim.rs: typed native calls for every DLL signature GM 8.1 allows.

Signatures: 0..4 arguments of any mix of real (f64) and string (char*), or 5..16
arguments all real; result real or string; cdecl or stdcall (stdcall only exists on
32-bit x86; elsewhere both map to the platform C convention).

Run: python crates/instance-dllcall/tools/gen_shim.py
"""
import itertools
import os

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "shim.rs")


def sigs():
    for n in range(0, 5):
        for combo in itertools.product("rs", repeat=n):
            yield "".join(combo)
    for n in range(5, 17):
        yield "r" * n


def arm(sig, ret, conv):
    tys = ", ".join("f64" if c == "r" else "*const c_char" for c in sig)
    args = ", ".join(f"a[{i}].{'real' if c == 'r' else 'ptr'}()" for i, c in enumerate(sig))
    rty = "f64" if ret == "r" else "*const c_char"
    wrap = "Ret::Real" if ret == "r" else "Ret::Ptr"
    mask = sum(1 << i for i, c in enumerate(sig) if c == "s")
    return (
        f"        ({len(sig)}, {mask}, {'true' if ret == 's' else 'false'}) => {{\n"
        f"            let f: unsafe extern \"{conv}\" fn({tys}) -> {rty} = std::mem::transmute(fp);\n"
        f"            {wrap}(f({args}))\n"
        f"        }}\n"
    )


def body(conv):
    s = ""
    for sig in sigs():
        for ret in "rs":
            s += arm(sig, ret, conv)
    s += "        _ => return None,\n"
    return s


def main():
    out = []
    out.append("// @generated by tools/gen_shim.py - do not edit by hand.\n")
    out.append("#![allow(clippy::all)]\n\n")
    out.append("use super::{Arg, Ret};\nuse std::ffi::{c_char, c_void};\n\n")
    out.append(
        "/// Calls `fp` with the C calling convention. `None` for an unsupported signature.\n"
        "///\n/// # Safety\n/// `fp` must point to a function with exactly this signature.\n"
        "pub unsafe fn call_c(fp: *const c_void, a: &[Arg], ret_str: bool) -> Option<Ret> {\n"
        "    let mask = super::string_mask(a);\n"
        "    Some(match (a.len(), mask, ret_str) {\n"
    )
    out.append(body("C"))
    out.append("    })\n}\n\n")
    out.append(
        "/// Calls `fp` with the stdcall convention (32-bit x86 only).\n"
        "///\n/// # Safety\n/// `fp` must point to a function with exactly this signature.\n"
        "#[cfg(target_arch = \"x86\")]\n"
        "pub unsafe fn call_stdcall(fp: *const c_void, a: &[Arg], ret_str: bool) -> Option<Ret> {\n"
        "    let mask = super::string_mask(a);\n"
        "    Some(match (a.len(), mask, ret_str) {\n"
    )
    out.append(body("stdcall"))
    out.append("    })\n}\n")
    with open(OUT, "w", newline="\n") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main()
