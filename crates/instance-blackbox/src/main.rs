fn manifest_md() -> String {
    let specs = projects::all();
    let mut s = String::new();
    s.push_str("# Black-box test manifest\n\n");
    s.push_str("Generated by `cargo run -p instance-blackbox -- manifest`; do not edit by hand.\n\n");
    s.push_str(
        "The generator (`crates/instance-blackbox`) writes small GM 8.1 projects that log observations\n\
         as `key=value` lines (on screen, to `results_<name>.txt`, and to the clipboard). The user\n\
         runs them in the real GameMaker 8.1 (Lite); `instance-blackbox run-ours` runs them in\n\
         instance-runner; `instance-blackbox compare <ours> <gm>` lists the differences together with the\n\
         question ids below (OPEN_QUESTIONS.md ids such as RT-08, GML-4, G-26; spec sections).\n\n",
    );
    s.push_str(
        "Conventions: strings are logged in double quotes, reals with up to 10 decimals\n\
         (`string_format` with trailing zeros removed, so independent of `string()`).\n\
         Tests that may raise an error log `key` (`\"<unset>\"` if the statement did not\n\
         complete), `key.err` (`error_occurred`) and `key.msg` (`error_last`); a test whose\n\
         whole event was abandoned logs `key.aborted=1` on the next step. Display of errors\n\
         is switched off in the generated settings so no dialog interrupts the run.\n\
         Event-sequence keys (`ev.sNN`, `in.sNN`, `rm.sNN`, ...) hold space-separated tags\n\
         `<instance>.<event>` for the step that ended (s00 = everything before the first\n\
         Begin Step); long sequences continue in `key+1`, `key+2`. Event tags: CR create,\n\
         IC instance creation code, CC room creation code, DE destroy, A<n> alarm (value of\n\
         alarm[n] inside the event in brackets), BS/ST/ES begin/normal/end step, DR draw, CO\n\
         collision, OR outside room, IB intersect boundary, AE animation end, PE path end,\n\
         RS/RE room start/end, GS/GE game start/end, NML/NMH no more lives/health, U0 user 0,\n\
         TL<n> timeline moment, TRbs/TRst/TRes trigger (begin/step/end moment), KP/KB/KR key\n\
         press/held/release, k.BS = the clock instance (first in instance order).\n\n",
    );
    for sp in &specs {
        s.push_str(&format!("## {} — {}\n\n", sp.name, sp.title));
        s.push_str(&format!("Lite: {}  \nHeadless frames for instance-runner: {}\n\n", sp.lite, sp.frames));
        s.push_str("| key prefix | answers | what is logged |\n|---|---|---|\n");
        for k in &sp.keys {
            s.push_str(&format!(
                "| `{}` | {} | {}{} |\n",
                k.prefix,
                k.ids,
                k.desc,
                if k.info { " (informational)" } else { "" }
            ));
        }
        s.push('\n');
    }
    s.push_str(
        "## Not covered\n\n\
         - D3D-*, surfaces, particles, blend modes, data structures, multiplayer, DLLs: Pro-only\n  \
           in GM 8.1 (the test machine has Lite).\n\
         - SND-1..5, SND-7 need audio measurement; JOY-* need a joystick; IDE-* and FF-* are\n  \
           about the editor and file contents (observe the IDE / save files instead). The\n  \
           Errors tab of bb_lang / bb_args0 (README step) answers FF-18 / IDE-12.\n\
         - Mouse events (RT-14) need real mouse input.\n",
    );
    s
}

/// Prints elapsed time, steps and every `perf.*` timing side by side with the
/// GM / ours ratio (> 1 means our runner is faster).
fn timing_table(ours: &BTreeMap<String, String>, gm: &BTreeMap<String, String>) {
    let num = |m: &BTreeMap<String, String>, k: &str| m.get(k).and_then(|v| v.parse::<f64>().ok());
    let mut rows = Vec::new();
    for k in ours.keys().chain(gm.keys()) {
        let timing = k == "meta.elapsed_ms" || k == "meta.steps" || (k.starts_with("perf.") && !k.ends_with(".n") && k != "perf.done");
        if !timing || rows.iter().any(|(r, _, _)| r == k) {
            continue;
        }
        rows.push((k.clone(), num(ours, k), num(gm, k)));
    }
    if rows.is_empty() {
        return;
    }
    println!("  -- timing (ours | GM 8.1 | GM/ours; for fps: ours/GM):");
    for (k, o, g) in rows {
        let f = |v: Option<f64>| v.map_or("-".to_string(), |v| format!("{v:.0}"));
        let ratio = match (o, g) {
            (Some(o), Some(g)) if k.contains("fps") && g > 0.0 => format!("{:.2}x", o / g),
            (Some(o), Some(g)) if o > 0.0 => format!("{:.2}x", g / o),
            _ => "-".to_string(),
        };
        println!("    {k:40} {:>8} | {:>8} | {ratio}", f(o), f(g));
    }
}
