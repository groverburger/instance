type Results = BTreeMap<String, String>;

/// Parses `key=value` lines; repeated keys get `#2`, `#3`... suffixes.
fn parse_results(text: &str) -> Results {
    let mut m = Results::new();
    for line in text.lines() {
        let line = line.trim_end_matches('\r');
        let Some(eq) = line.find('=') else { continue };
        let (k, v) = (&line[..eq], &line[eq + 1..]);
        let mut key = k.to_string();
        let mut n = 1;
        while m.contains_key(&key) {
            n += 1;
            key = format!("{k}#{n}");
        }
        m.insert(key, v.to_string());
    }
    m
}

fn doc_for<'a>(docs: &'a [KeyDoc], key: &str) -> Option<&'a KeyDoc> {
    let base = key.split('#').next().unwrap_or(key);
    // suffix rules (".msg", ".err", ".aborted") first
    if let Some(d) = docs
        .iter()
        .filter(|d| d.prefix.starts_with('.'))
        .find(|d| base.ends_with(d.prefix))
    {
        if d.prefix != ".err" {
            return Some(d);
        }
        // .err belongs to the test's own question ids
        if let Some(own) = doc_for(docs, base.trim_end_matches(".err")) {
            return Some(own);
        }
        return Some(d);
    }
    docs.iter()
        .filter(|d| !d.prefix.starts_with('.') && base.starts_with(d.prefix))
        .max_by_key(|d| d.prefix.len())
}

fn compare(ours: &Path, gm: &Path) -> i32 {
    let specs = projects::all();
    let mut total_mismatch = 0;
    let mut per_q: BTreeMap<String, (usize, usize)> = BTreeMap::new();
    for s in &specs {
        let file = format!("results_{}.txt", s.name);
        let a = std::fs::read(ours.join(&file)).ok();
        let b = std::fs::read(gm.join(&file)).ok();
        let (Some(a), Some(b)) = (a, b) else {
            println!(
                "== {}: {}",
                s.name,
                match (ours.join(&file).exists(), gm.join(&file).exists()) {
                    (false, false) => "no results on either side",
                    (false, true) => "no results from our runner",
                    (true, false) => "no GM results",
                    _ => "unreadable",
                }
            );
            continue;
        };
        let a = parse_results(&String::from_utf8_lossy(&a));
        let b = parse_results(&String::from_utf8_lossy(&b));
        let mut keys: Vec<&String> = a.keys().chain(b.keys()).collect();
        keys.sort();
        keys.dedup();
        let mut lines = Vec::new();
        let mut info = Vec::new();
        let (mut same, mut diff) = (0, 0);
        for k in keys {
            if k.starts_with("meta.") {
                continue;
            }
            let (va, vb) = (a.get(k), b.get(k));
            let doc = doc_for(&s.keys, k);
            let ids = doc.map_or("?", |d| d.ids);
            let is_info = doc.is_some_and(|d| d.info);
            let entry = per_q.entry(ids.to_string()).or_default();
            if va == vb {
                same += 1;
                if !is_info {
                    entry.0 += 1;
                }
                continue;
            }
            let fmt = |v: Option<&String>| v.map_or("<missing>".to_string(), |v| v.clone());
            let line = format!("  {k}\n      ours: {}\n      gm:   {}\n      [{ids}]", fmt(va), fmt(vb));
            if is_info {
                info.push(line);
            } else {
                diff += 1;
                entry.1 += 1;
                lines.push(line);
            }
        }
        total_mismatch += diff;
        println!("== {}: {} equal, {} different, {} informational differences", s.name, same, diff, info.len());
        for l in lines {
            println!("{l}");
        }
        if !info.is_empty() {
            println!("  -- informational (locale/wording/timing):");
            for l in info {
                println!("{l}");
            }
        }
        timing_table(&a, &b);
    }
    println!("\n== per question group (equal / different)");
    for (q, (s, d)) in per_q {
        if s + d > 0 {
            println!("  {:>4} / {:<4} {q}", s, d);
        }
    }
    if total_mismatch > 0 {
        1
    } else {
        0
    }
}

