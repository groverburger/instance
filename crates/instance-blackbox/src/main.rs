fn run_ours(dir: &Path, runner: Option<PathBuf>, only: Option<String>) -> i32 {
    let runner = runner.unwrap_or_else(|| {
        let exe = std::env::current_exe().unwrap();
        exe.with_file_name(if cfg!(windows) { "instance-runner.exe" } else { "instance-runner" })
    });
    let ours = dir.join("ours");
    let _ = std::fs::create_dir_all(&ours);
    let mut failures = 0;
    for s in projects::all() {
        if only.as_deref().is_some_and(|o| o != s.name) {
            continue;
        }
        let src = dir.join(format!("{}.gm81", s.name));
        let game = ours.join(format!("{}.gm81", s.name));
        if let Err(e) = std::fs::copy(&src, &game) {
            eprintln!("{}: {e} (run generate first)", src.display());
            failures += 1;
            continue;
        }
        let result = ours.join(format!("results_{}.txt", s.name));
        let _ = std::fs::remove_file(&result);
        let out = std::process::Command::new(&runner)
            .arg(&game)
            .arg("--headless")
            .arg("--frames")
            .arg(s.frames.to_string())
            .arg("--max-seconds")
            // bb_perf_fps runs for wall-clock time and saves after ~4 s
            .arg(if s.name == "bb_perf_fps" { "10" } else { "300" })
            // GM 8.1 draws with Direct3D; compare frame rates against our GPU renderer
            .args(if s.name == "bb_perf_fps" { &["--renderer", "gl"][..] } else { &[][..] })
            .current_dir(&ours)
            .output();
        let _ = std::fs::remove_file(&game);
        let _ = std::fs::remove_file(ours.join("bb_restart_marker.txt"));
        match out {
            Ok(o) => {
                let mut log = o.stdout.clone();
                log.extend_from_slice(&o.stderr);
                let _ = std::fs::write(ours.join(format!("runner_{}.log", s.name)), &log);
                let ok = result.exists();
                println!(
                    "{:14} exit={:?} results={}",
                    s.name,
                    o.status.code(),
                    if ok { "yes" } else { "MISSING" }
                );
                if !ok {
                    failures += 1;
                }
            }
            Err(e) => {
                eprintln!("{}: cannot run {}: {e}", s.name, runner.display());
                failures += 1;
            }
        }
    }
    if failures > 0 {
        1
    } else {
        0
    }
}

