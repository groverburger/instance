//! instance-blackbox: generates GameMaker 8.1 black-box test projects, runs them in
//! instance-runner and compares result files.
//!
//! ```text
//! instance-blackbox generate <dir>                 write the .gm81 projects + README.txt
//! instance-blackbox run-ours <dir> [--runner EXE]  run each project headless, results -> <dir>/ours
//! instance-blackbox compare <ours_dir> <gm_dir>    print mismatches with the questions they answer
//! instance-blackbox manifest                       print the key manifest (specs/blackbox-tests.md)
//! ```

mod builder;
mod framework;
mod projects;

use framework::{KeyDoc, Spec};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let code = match args.first().map(|s| s.as_str()) {
        Some("generate") if args.len() == 2 => generate(Path::new(&args[1])),
        Some("run-ours") if args.len() >= 2 => {
            let mut runner = None;
            let mut only = None;
            let mut i = 2;
            while i < args.len() {
                match args[i].as_str() {
                    "--runner" => {
                        runner = args.get(i + 1).map(PathBuf::from);
                        i += 1;
                    }
                    "--only" => {
                        only = args.get(i + 1).cloned();
                        i += 1;
                    }
                    _ => {}
                }
                i += 1;
            }
            run_ours(Path::new(&args[1]), runner, only)
        }
        Some("compare") if args.len() == 3 => compare(Path::new(&args[1]), Path::new(&args[2])),
        Some("manifest") => {
            print!("{}", manifest_md());
            0
        }
        _ => {
            eprintln!("usage:\n  instance-blackbox generate <dir>\n  instance-blackbox run-ours <dir> [--runner instance-runner.exe] [--only NAME]\n  instance-blackbox compare <ours_dir> <gm_dir>\n  instance-blackbox manifest");
            2
        }
    };
    std::process::exit(code);
}

fn generate(dir: &Path) -> i32 {
    if let Err(e) = std::fs::create_dir_all(dir) {
        eprintln!("cannot create {}: {e}", dir.display());
        return 1;
    }
    let specs = projects::all();
    for s in &specs {
        let path = dir.join(format!("{}.gm81", s.name));
        let bytes = match instance_format::write_project(&s.project, instance_format::FormatVersion::V810) {
            Ok(b) => b,
            Err(e) => {
                eprintln!("{}: write failed: {e}", s.name);
                return 1;
            }
        };
        // must read back identically
        match instance_format::read_project(&bytes) {
            Ok(p) if p == s.project => {}
            Ok(_) => {
                eprintln!("{}: read-back differs from the generated model", s.name);
                return 1;
            }
            Err(e) => {
                eprintln!("{}: read-back failed: {e}", s.name);
                return 1;
            }
        }
        if let Err(e) = std::fs::write(&path, bytes) {
            eprintln!("{}: {e}", path.display());
            return 1;
        }
        let objs = s.project.objects.len();
        println!("wrote {} ({} objects, {} rooms)", path.display(), objs, s.project.rooms.len());
    }
    let readme = readme(&specs);
    if let Err(e) = std::fs::write(dir.join("README.txt"), readme.replace('\n', "\r\n")) {
        eprintln!("README: {e}");
        return 1;
    }
    println!("wrote {}", dir.join("README.txt").display());
    0
}

