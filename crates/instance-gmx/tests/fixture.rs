fn fixture_dir(tag: &str) -> PathBuf {
    let d = std::env::temp_dir().join(format!("instance-gmx-fixture-{}-{tag}", std::process::id())).join("Tiny.gmx");
    let _ = std::fs::remove_dir_all(&d);
    write_fixture(&d);
    d
}

fn obj<'a>(p: &'a Project, name: &str) -> (usize, &'a Object) {
    p.objects
        .iter()
        .enumerate()
        .find_map(|(i, o)| o.as_ref().filter(|o| o.name == name).map(|o| (i, o)))
        .unwrap_or_else(|| panic!("object {name}"))
}

fn code_of(e: &Event) -> String {
    e.actions.iter().filter(|a| a.kind == action_kind::CODE).map(|a| a.args[0].clone()).collect::<Vec<_>>().join("\n")
}

fn check(p: &Project, warnings: &[instance_gmx::Warning]) {
    let warn_text: String = warnings.iter().map(|w| format!("{w}\n")).collect();
    // Settings and metadata.
    assert_eq!(p.game_id, 12345);
    assert_eq!(p.guid[0], 0xF2);
    assert!(p.settings.interpolate_pixels);
    assert_eq!(p.settings.author, "Tester");
    assert_eq!(p.settings.version_major, 2);
    assert!(p.settings.treat_uninitialized_as_zero);
    assert!(p.game_info.rtf.contains("Tiny test game"));
    let consts: Vec<(&str, &str)> = p.constants.iter().map(|c| (c.name.as_str(), c.value.as_str())).collect();
    assert!(consts.contains(&("SPEED", "4")));
    assert!(consts.contains(&("CFG_VALUE", "7")));
    // Included file.
    assert_eq!(p.included_files.len(), 1);
    assert_eq!(p.included_files[0].data.as_deref(), Some(&b"1,2,3"[..]));

    // Sound.
    let snd = p.sounds[0].as_ref().unwrap();
    assert_eq!(snd.name, "sndBeep");
    assert_eq!(snd.file_type, ".wav");
    assert_eq!(snd.volume, 0.5);
    assert!(snd.data.as_ref().unwrap().starts_with(b"RIFF"));

    // Sprites (tree order: sBall, sWall, then the generated glyph sprite).
    let ball = p.sprites[0].as_ref().unwrap();
    assert_eq!(ball.name, "sBall");
    assert_eq!((ball.origin_x, ball.origin_y), (4, 4));
    assert_eq!(ball.frames.len(), 2);
    assert_eq!(ball.frames[0].pixel(4, 4), [255, 0, 0, 255]);
    assert_eq!(ball.frames[0].pixel(0, 0)[3], 0);
    assert_eq!((ball.collision_shape, ball.bbox_mode, ball.bbox_right), (0, 2, 6));
    assert_eq!(p.sprites[1].as_ref().unwrap().name, "sWall");
    let glyphs = p.sprites[2].as_ref().unwrap();
    assert_eq!(glyphs.name, "__gmx_font_fntSmall");
    assert_eq!(glyphs.frames.len(), 2);
    // '!' glyph at offset 1; advance markers at columns 0 and 3.
    assert_eq!(glyphs.frames[1].pixel(1, 0), [255, 255, 255, 255]);
    assert_eq!(glyphs.frames[1].pixel(3, 0)[3], 1);

    // Background, path, font, timeline.
    let bg = p.backgrounds[0].as_ref().unwrap();
    assert!(bg.use_as_tileset);
    assert_eq!((bg.image.width, bg.image.height), (32, 16));
    let path = p.paths[0].as_ref().unwrap();
    assert_eq!(path.connection_kind, 1);
    assert_eq!(path.points.len(), 3);
    assert_eq!(path.points[2].speed, 50.0);
    let font = p.fonts[0].as_ref().unwrap();
    assert_eq!((font.font_name.as_str(), font.size, font.antialias), ("Arial", 8, 3));
    assert_eq!((font.range_start, font.range_end), (32, 33));
    let tl = p.timelines[0].as_ref().unwrap();
    assert_eq!(tl.moments.iter().map(|m| m.step).collect::<Vec<_>>(), vec![0, 10]);

    // Scripts: #define split, Studio syntax translated, compat scripts injected.
    let names: Vec<&str> = p.scripts.iter().flatten().map(|s| s.name.as_str()).collect();
    assert_eq!(&names[..3], &["util_first", "util_second", "scrDouble"]);
    let s2 = &p.scripts[1].as_ref().unwrap().code;
    assert!(s2.contains("var a, b; a = argument0; b = 2"), "{s2}");
    assert!(names.contains(&"audio_play_sound"), "{names:?}");
    assert!(names.contains(&"__gmx_ds_map_set") || !names.contains(&"ds_map_set"));

    // Objects.
    let (ball_i, ball_o) = obj(p, "oBall");
    let (wall_i, wall_o) = obj(p, "oWall");
    let (_, hud) = obj(p, "oHud");
    assert_eq!(ball_o.depth, -5);
    assert_eq!(wall_o.parent, NO_PARENT, "parent 'self' means none");
    assert_eq!(hud.parent, ball_i as i32);
    assert_eq!(hud.mask_sprite, 1);
    assert!(ball_o.event(event_type::COLLISION, wall_i as i32).is_some());
    let step = code_of(ball_o.event(event_type::STEP, 0).unwrap());
    assert!(!step.contains("++") && step.contains("hits += 1"), "{step}");
    assert!(step.contains("ds_list_replace(l, 0, __gmx_t"), "{step}");
    assert!(step.contains("if (oWall.x > 0)"), "short-circuit: {step}");
    let var_act = &ball_o.event(event_type::STEP, 0).unwrap().actions[1];
    assert_eq!(var_act.kind, action_kind::VARIABLE);
    assert_eq!(var_act.applies_to, APPLIES_TO_OTHER);
    assert!(var_act.relative);
    assert_eq!(var_act.args[1], "$10");
    // Draw End merged into Draw, with default drawing first.
    let draw = code_of(ball_o.event(event_type::DRAW, 0).unwrap());
    assert!(draw.contains("draw_sprite_ext") && draw.contains("draw_circle"), "{draw}");
    // Create moved to user event 14 because an instance has creation code.
    let create = code_of(ball_o.event(event_type::CREATE, 0).unwrap());
    assert!(create.contains("event_perform(ev_other, ev_user14)"), "{create}");
    let moved = code_of(ball_o.event(event_type::OTHER, 24).unwrap());
    assert!(moved.contains("dir = 1;"), "enum inlined: {moved}");
    // Draw GUI moved to user event 15 and a controller added.
    let gui = code_of(ball_o.event(event_type::OTHER, 25).unwrap());
    assert!(gui.contains("draw_text(4, 4"), "{gui}");
    let (ctrl_i, ctrl) = obj(p, "__gmx_gui_controller");
    assert!(code_of(ctrl.event(event_type::DRAW, 0).unwrap()).contains("with (oBall) if (visible) event_perform(ev_other, ev_user15)"));

    // Room.
    let room = p.rooms[0].as_ref().unwrap();
    assert_eq!((room.width, room.height, room.speed), (320, 240, 60));
    assert_eq!(room.caption, "Tiny Game");
    assert!(room.views_enabled);
    assert_eq!(room.views[0].follow_object, ball_i as i32);
    assert_eq!(room.backgrounds[0].background, 0);
    assert!(!room.backgrounds[0].tile_v);
    assert!(room.creation_code.contains("global.level = 1;"));
    assert!(room.creation_code.contains("tile_set_scale("), "{}", room.creation_code);
    assert!(room.creation_code.contains("font_replace_sprite(0, 2, 32, true, 0)"));
    // 3 placed instances (unknown object dropped) + GUI controller.
    assert_eq!(room.instances.len(), 4);
    assert_eq!(room.instances[3].object, ctrl_i as i32);
    let cc = &room.instances[0].creation_code;
    assert!(cc.starts_with("image_xscale = 2;image_angle = 45;image_blend = 255;"), "{cc}");
    assert!(cc.contains("event_perform(ev_other, ev_user14); __gmx_cc_done = true;\r\nspeed = 8;"), "{cc}");
    // All code uses CR LF line endings, like GM-saved code.
    let lone_lf = |c: &str| c.replace("\r\n", "").contains('\n');
    assert!(!p.scripts.iter().flatten().any(|s| lone_lf(&s.code)));
    assert!(!p.rooms.iter().flatten().any(|r| lone_lf(&r.creation_code) || r.instances.iter().any(|i| lone_lf(&i.creation_code))));
    assert_eq!(room.tiles.len(), 1);
    assert_eq!((room.tiles[0].tile_x, room.tiles[0].background), (16, 0));

    // Resource tree keeps groups.
    let sprites = p.resource_tree.iter().find(|n| n.kind == ResourceKind::Sprite).unwrap();
    assert_eq!(sprites.children[0].status, NodeStatus::Group);
    assert_eq!(sprites.children[0].name, "Player");
    assert_eq!(sprites.children[0].children[0].name, "sBall");
    let scripts = p.resource_tree.iter().find(|n| n.kind == ResourceKind::Script).unwrap();
    assert_eq!(scripts.children[0].name, "util_first");
    assert_eq!(scripts.children[1].name, "util_second");
    assert_eq!(scripts.children[2].name, "Math");

    // Warnings mention dropped features.
    assert!(warn_text.contains("shGlow"), "{warn_text}");
    assert!(warn_text.contains("oMissing"), "{warn_text}");
    assert!(warn_text.contains("7/62"), "{warn_text}");
}

#[test]
fn loads_directory() {
    let d = fixture_dir("dir");
    let (p, w) = instance_gmx::load_gmx(&d).unwrap();
    check(&p, &w);
    // Also via the project file path.
    let (p2, _) = instance_gmx::load_gmx(d.join("Tiny.project.gmx")).unwrap();
    assert_eq!(p2.objects.len(), p.objects.len());
}

#[test]
fn roundtrips_through_gm81() {
    let d = fixture_dir("rt");
    let (p, _) = instance_gmx::load_gmx(&d).unwrap();
    let bytes = instance_format::write_project(&p, instance_format::FormatVersion::V810).unwrap();
    let back = instance_format::read_project(&bytes).unwrap();
    assert_eq!(back.objects.len(), p.objects.len());
    assert_eq!(back.scripts, p.scripts);
    assert_eq!(back.rooms, p.rooms);
    assert_eq!(back.resource_tree, p.resource_tree);
}

fn zip_dir(dir: &Path, out: &Path) {
    use std::io::Write;
    let f = std::fs::File::create(out).unwrap();
    let mut z = zip::ZipWriter::new(f);
    let opts: zip::write::SimpleFileOptions = zip::write::SimpleFileOptions::default();
    fn walk(base: &Path, d: &Path, z: &mut zip::ZipWriter<std::fs::File>, opts: zip::write::SimpleFileOptions) {
        for e in std::fs::read_dir(d).unwrap().flatten() {
            let p = e.path();
            if p.is_dir() {
                walk(base, &p, z, opts);
            } else {
                // Studio archives use backslashes and a top-level folder.
                let rel = p.strip_prefix(base).unwrap().to_string_lossy().replace('/', "\\");
                z.start_file(format!("Tiny.gmx\\{rel}"), opts).unwrap();
                z.write_all(&std::fs::read(&p).unwrap()).unwrap();
            }
        }
    }
    walk(dir, dir, &mut z, opts);
    z.finish().unwrap();
}

#[test]
fn loads_zip_gmz() {
    let d = fixture_dir("zip");
    let gmz = d.parent().unwrap().join("Tiny.gmz");
    zip_dir(&d, &gmz);
    let (p, w) = instance_gmx::load_gmx(&gmz).unwrap();
    check(&p, &w);
}

