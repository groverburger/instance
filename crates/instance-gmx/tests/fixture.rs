fn png(w: u32, h: u32, f: impl Fn(u32, u32) -> [u8; 4]) -> Vec<u8> {
    let mut out = Vec::new();
    {
        let mut enc = png::Encoder::new(&mut out, w, h);
        enc.set_color(png::ColorType::Rgba);
        enc.set_depth(png::BitDepth::Eight);
        let mut wr = enc.write_header().unwrap();
        let mut data = Vec::new();
        for y in 0..h {
            for x in 0..w {
                data.extend_from_slice(&f(x, y));
            }
        }
        wr.write_image_data(&data).unwrap();
    }
    out
}

fn wav() -> Vec<u8> {
    let samples: Vec<u8> = (0..64).map(|i| if i % 8 < 4 { 0x40 } else { 0xC0 }).collect();
    let mut v = Vec::new();
    v.extend_from_slice(b"RIFF");
    v.extend_from_slice(&(36 + samples.len() as u32).to_le_bytes());
    v.extend_from_slice(b"WAVEfmt ");
    v.extend_from_slice(&16u32.to_le_bytes());
    v.extend_from_slice(&1u16.to_le_bytes()); // PCM
    v.extend_from_slice(&1u16.to_le_bytes()); // mono
    v.extend_from_slice(&8000u32.to_le_bytes());
    v.extend_from_slice(&8000u32.to_le_bytes());
    v.extend_from_slice(&1u16.to_le_bytes());
    v.extend_from_slice(&8u16.to_le_bytes());
    v.extend_from_slice(b"data");
    v.extend_from_slice(&(samples.len() as u32).to_le_bytes());
    v.extend_from_slice(&samples);
    v
}

const HDR: &str = "<!--This Document is generated by GameMaker, if you edit it by hand then you do so at your own risk!-->\n";

fn code_action(code: &str) -> String {
    let code = code.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;");
    format!(
        "<action><libid>1</libid><id>603</id><kind>7</kind><userelative>0</userelative><isquestion>0</isquestion>\
         <useapplyto>-1</useapplyto><exetype>2</exetype><functionname></functionname><codestring></codestring>\
         <whoName>self</whoName><relative>0</relative><isnot>0</isnot><arguments><argument><kind>1</kind>\
         <string>{code}</string></argument></arguments></action>"
    )
}

